import ProductLibraryView from "@/views/inventory/ProductLibraryView"
import ModuleContainer from "../../ModuleContainer"
import { shopId, type ShopId } from "@/types/shop";
import { useCurrentShopSlice, useShopProducts } from "@/hooks/shop/useShopProducts";
import  { useShopStore, type ShopMeta } from "@/store/shop/useShopStore";
import {  useState } from "react";
import Info from "@/views/ABCViews/info/Info";
import { Button } from "@/components/ui/Button";
import { useApiErrorToast } from "@/services/api/useApiErrorToast";
import CreateShopDialog from "@/components/layout/context/CreateShopDialog";
import { useImportShopProducts } from "@/views/inventory/hooks/useImportShopProducts";
import { useProductStore } from "@/store/inventory/useProductStore";


const AUTOGEN_SHOPS = [
  { label: "Florist shop", id: shopId("FLORIST") },
  { label: "Cafeteria", id: shopId("CAFETERIA") },  
   ];

const PRODUCT_LIBRARY_INFO = {
  title: "Product Library",
  theory: "Shop-based inventory view",
  description:
    "You are managing the product catalog for the selected shop. Switch shops using the selector above to explore different inventories or create you own shop.",
}


const ProductLibraryModule = () => {  
  const [open, setOpen] = useState(false);
  const [selectedShop, setSelectedShop] = useState<ShopId | null>(null);
  const [shouldLoad, setShouldLoad] = useState(false);

   const { shop, setShop } = useShopStore((s) => ({
    shop: s.shop,
    setShop: s.setShop,
  }));

  const userProducts = useProductStore((s) => s.products);

  const { products: autoProducts, loading, error } = useShopProducts(selectedShop, {
    enabled: shouldLoad,
  });

  const { importProducts } = useImportShopProducts();

  // --- When a shop is selected from the menu ---
  const handleShopChange = (shopId: ShopId) => {
    setSelectedShop(shopId);
    setShop({ id: shopId, name: AUTOGEN_SHOPS.find((s) => s.id === shopId)?.label || shopId });
    setShouldLoad(true);
  };

  // --- When a new shop is created ---
  const handleCreateShop = (shop: ShopMeta) => {
  setShop(shop);

  // Ask if user wants to import from selected autogenerated shop
  if (selectedShop && autoProducts.length > 0) {
    const sourceLabel =
      selectedShop === shopId("FLORIST") ? "Florist shop" : "Cafeteria";

    if (
      window.confirm(
        `Do you want to import ${autoProducts.length} products from ${sourceLabel} into "${shop.name}"?`
      )
    ) {
      importProducts(autoProducts);
    }
  }
};


  // --- Decide which products to show in the ProductLibraryView ---
  let productsToShow = userProducts;
  if (selectedShop) {
    productsToShow = autoProducts;
  }

  // Show toast when API fails
  useApiErrorToast(error, `Shop: ${selectedShop}`);


  // console.log("inventory ", products, " loading ", loading)
  //Make the user to create a new shop to have its own product store
  return (
    <ModuleContainer
            title="Product Library"
            subtitle="Manage your products efficiently"
            breadcrumbTrail={[
              { label: "Dashboard", path: "/dashboard" },
              { label: "Inventory", path: "/dashboard/inventory" },
              { label: "Product Library" },
            ]}
            userCases={[
             ...AUTOGEN_SHOPS.map((s) => s.label),
             ...(userProducts.length > 0 && shop ? [shop.name] : []),
          ]}//import different user cases as needed
            userCasesPlaceholder="Import data shop"
            onUserCaseChange={(label) => {
              const autoShop = AUTOGEN_SHOPS.find((s) => s.label === label);
              if (autoShop) {
                handleShopChange(autoShop.id);
                return;
              }
              // user shop
              if (userProducts.length > 0 && shop?.name === label) {
                setSelectedShop(null); // show user products
              } else {
                console.warn("Cannot select a shop without products");
              }
            }}
            actions={
              <>
                <Info content={PRODUCT_LIBRARY_INFO} />

                <Button 
                 className="toolbar-element jbtn-flat-btn toolbar-element-md active"
                 onClick={() => setOpen(true)}>
                  Create shop
                </Button>
                
                <Button className="toolbar-element jbtn-flat-btn toolbar-element-md">
                  Helpers
                </Button>
              </>
            }
          >
             <CreateShopDialog
                open={open}
                onOpenChange={setOpen}
                onCreated={(shop) => handleCreateShop(shop)}
              />
             {/* Product view: only user products */}
             {shop && (
              <ProductLibraryView
                shopId={shop.id}
                shopName={shop.name}
                products={productsToShow}
                loading={loading}
              />
            )}


      </ModuleContainer>

      
  )
}

export default ProductLibraryModule