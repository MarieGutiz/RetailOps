import ProductLibraryView from "@/views/inventory/ProductLibraryView"
import ModuleContainer from "../../ModuleContainer"
import { shopId, type ShopId } from "@/types/shop";
import { useShopProducts } from "@/hooks/shop/useShopProducts";
import  { useShopStore, type ShopMeta } from "@/store/shop/useShopStore";
import {  useState } from "react";
import Info from "@/views/ABCViews/info/Info";
import { Button } from "@/components/ui/Button";
import { useImportShopProducts } from "@/views/inventory/hooks/useImportShopProducts";
import { useProductStore } from "@/store/inventory/useProductStore";
import { useShallow } from "zustand/react/shallow";
import ServiceUnavailable from "@/views/inventory/forms/ServiceUnavailable";
import ShopCreationWizardDialog from "@/views/inventory/forms/ShopCreationWizardDialog";

const AUTOGEN_SHOPS = [
  { id: shopId("FLORIST"), label: "Florist shop", source: "florist" as const },
  { id: shopId("CAFETERIA"), label: "Cafeteria", source: "cafeteria" as const },
];

const PRODUCT_LIBRARY_INFO = {
  title: "Product Library",
  theory: "Shop-based inventory view",
  description:
    "You are managing the product catalog for the selected shop. Switch shops using the selector above to explore different inventories or create you own shop.",
}

type LibrarySelection =
  | { type: "autogen"; shopId: ShopId }
  | { type: "user" }
  | null;


const ProductLibraryModule = () => {  
  //Flow state
  const [wizardOpen, setWizardOpen] = useState(false);

  const [selection, setSelection] = useState<LibrarySelection>(null);

  //Store binding
  const { shop, setShop } = useShopStore(
    useShallow((s) => ({
      shop: s.shop,
      setShop: s.setShop,
    }))
  );

  const userProducts = useProductStore((s) => s.products);

  //Autogenerated shops data
  const florist = useShopProducts(shopId("FLORIST"));
  const cafeteria = useShopProducts(shopId("CAFETERIA"));

  const backendUnavailable = Boolean(florist.error || cafeteria.error);
 
  // Conditional autogen fecthing
  const autogenShopId =
  selection?.type === "autogen" ? selection.shopId : null;

  const { products: autoProducts, loading } = useShopProducts(
    autogenShopId,
    {
      enabled: selection?.type === "autogen",
    }
  );


  //Handlers
  // --- Autogenerated selection ---
  const handleAutogenSelect = (shopId: ShopId) => {
    const meta = AUTOGEN_SHOPS.find((s) => s.id === shopId)!;

    setSelection({ type: "autogen", shopId });
    setShop({ id: shopId, name: meta.label });
  };

  // --- User shop selection ---
  const handleUserSelect = () => {
    setSelection({ type: "user" });
  };
  

  // --- View state ---
  const productsToShow =
    selection?.type === "autogen" ? autoProducts : userProducts;

  const readonly = selection?.type === "autogen";

  const autogeneratedSource =
    selection?.type === "autogen"
      ? AUTOGEN_SHOPS.find((s) => s.id === selection.shopId)?.source
      : undefined;

  return (
    <ModuleContainer
            title="Product Library"
            subtitle="Manage your products efficiently"
            breadcrumbTrail={[
              { label: "Dashboard", path: "/dashboard" },
              { label: "Inventory", path: "/dashboard/inventory" },
              { label: "Product Library" },
            ]}
            userCases={[
             ...AUTOGEN_SHOPS.map((s) => s.label),
             ...(shop ? [shop.name] : []),
          ]}//import different user cases as needed
            userCasesPlaceholder="Import data shop"
            onUserCaseChange={(label) => {
              const auto = AUTOGEN_SHOPS.find((s) => s.label === label);
              if (auto) return handleAutogenSelect(auto.id);
              if (shop?.name === label) return handleUserSelect();
            }}
            actions={
              <>
                <Info content={PRODUCT_LIBRARY_INFO} />

                <Button 
                 className="toolbar-element jbtn-flat-btn toolbar-element-md active"
                 onClick={() => setWizardOpen(true)}>
                  Create shop
                </Button>
                
                <Button className="toolbar-element jbtn-flat-btn toolbar-element-md">
                  Helpers
                </Button>
              </>
            }
          >
              {/* Wizard dialog */}
              <ShopCreationWizardDialog
                open={wizardOpen}
                onOpenChange={setWizardOpen}
              />
                         
             {/* If server is down */}
              {selection?.type === "autogen" && backendUnavailable && (
                <ServiceUnavailable onCreateShop={() => setWizardOpen(true)} />
              ) }

             {/* Product view*/}
             
              <ProductLibraryView
                ShopMeta={shop ?? undefined}
                products={productsToShow}
                loading={loading}
                readonly={readonly}
                autogeneratedSource={autogeneratedSource}
              />

      </ModuleContainer>
      
  )
}

export default ProductLibraryModule